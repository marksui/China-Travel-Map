import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const args = parseArgs(process.argv.slice(2));

if (!args.id && !args.name) {
  fail("Pass --id or --name");
}
if (!args.url || !args.pageUrl || !args.caption) {
  fail("Pass --url, --page-url, and --caption");
}

function parseArgs(values) {
  const result = {};
  for (let index = 0; index < values.length; index += 1) {
    const key = values[index];
    const value = values[index + 1];
    if (!key.startsWith("--") || value == null) continue;
    result[key.slice(2).replace(/-([a-z])/g, (_, letter) => letter.toUpperCase())] = value;
    index += 1;
  }
  return result;
}

function fail(message) {
  console.error(`Usage: node scripts/add-4a-image.mjs --id <id> --url <assets/...jpg> --page-url <url> --caption <caption>\n${message}`);
  process.exit(1);
}

function readJsValue(file, marker, endMarker = null) {
  const text = fs.readFileSync(path.join(root, file), "utf8");
  const start = text.indexOf(marker);
  if (start < 0) throw new Error(`Missing marker ${marker} in ${file}`);
  const valueStart = start + marker.length;
  let valueEnd = endMarker ? text.indexOf(endMarker, valueStart) : text.indexOf(";\n", valueStart);
  if (valueEnd < 0) valueEnd = text.lastIndexOf(";");
  return JSON.parse(text.slice(valueStart, valueEnd).trim().replace(/;$/, ""));
}

function imageExists(entry) {
  const url = entry?.url || "";
  return url.startsWith("assets/images/") && fs.existsSync(path.join(root, url));
}

function sortManifest(manifest, attractions) {
  const order = new Map(attractions.map((item, index) => [item.id, index]));
  return Object.fromEntries(
    Object.entries(manifest).sort(([left], [right]) => (order.get(left) ?? 999999) - (order.get(right) ?? 999999)),
  );
}

function buildMissing(manifest, attractions) {
  return attractions
    .filter((item) => !(item.id in manifest) || !imageExists(manifest[item.id]))
    .map((item) => ({
      id: item.id,
      province: item.province,
      city: item.city,
      name: item.name,
      reason: "not fetched yet or no reliable open image candidate",
    }));
}

function buildSources(manifest, attractions) {
  const byId = new Map(attractions.map((item) => [item.id, item]));
  const lines = [
    "# 4A 图片来源",
    "",
    "本文档记录 4A 景区本地插图来源。脚本只写入已找到可靠开放来源并保存到本地的图片。",
    "",
    "| ID | 景点 | 本地文件 | 来源 | 来源页面 |",
    "| --- | --- | --- | --- | --- |",
  ];

  for (const [id, item] of Object.entries(manifest)) {
    const attraction = byId.get(id);
    const caption = (item.caption || "").replace(/\|/g, "/");
    lines.push(
      `| ${id} | ${attraction?.name || id} | \`${item.url || ""}\` | ${caption} | [链接](${item.pageUrl || ""}) |`,
    );
  }

  return `${lines.join("\n")}\n`;
}

const attractions = readJsValue("data/attractions-4a.js", "window.CHINA_4A_ATTRACTIONS = ", ";\nwindow.CHINA_4A_META");
const manifest = readJsValue("data/attraction-images-4a.js", "window.CHINA_4A_IMAGES = ");
const attraction = args.id
  ? attractions.find((item) => item.id === args.id)
  : attractions.find((item) => item.name === args.name);

if (!attraction) {
  fail(`Unknown 4A attraction: ${args.id || args.name}`);
}
if (!args.url.startsWith("assets/images/")) {
  fail("--url must be a local assets/images path");
}
if (!fs.existsSync(path.join(root, args.url))) {
  fail(`Local image not found: ${args.url}`);
}

manifest[attraction.id] = {
  url: args.url,
  pageUrl: args.pageUrl,
  caption: args.caption,
};

const orderedManifest = sortManifest(manifest, attractions);
fs.writeFileSync(
  path.join(root, "data/attraction-images-4a.js"),
  `// Generated by scripts/build-4a-images.py. Do not edit by hand.\nwindow.CHINA_4A_IMAGES = ${JSON.stringify(
    orderedManifest,
    null,
    2,
  )};\n`,
  "utf8",
);
fs.writeFileSync(
  path.join(root, "data/attraction-images-4a-missing.json"),
  `${JSON.stringify(buildMissing(orderedManifest, attractions), null, 2)}\n`,
  "utf8",
);
fs.writeFileSync(path.join(root, "assets/images/SOURCES-4A.md"), buildSources(orderedManifest, attractions), "utf8");

console.log(JSON.stringify({ added: attraction.id, manifest: Object.keys(orderedManifest).length }, null, 2));
