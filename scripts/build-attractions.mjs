function parseMarkdown(text) {
  let province = "";
  const attractions = [];

  for (const line of text.split(/\r?\n/)) {
    const heading = line.match(/^###\s+(.+?)\s+`(\d+)`/);
    if (heading) {
      province = heading[1].trim();
      continue;
    }

    const item = line.match(/^[-*]\s+(.+?)\s+`(\d{4})`/);
    if (!item || province === "全国") continue;

    attractions.push({
      province,
      name: item[1].trim(),
      year: Number(item[2]),
    });
  }

  return attractions;
}

